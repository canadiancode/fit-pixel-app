const fs = require("fs");
const path = require("path");
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
} = require("expo/config-plugins");

const RATIONALE_ACTION = "androidx.health.ACTION_SHOW_PERMISSIONS_RATIONALE";
const ACTIVITY_NAME = "HealthPermissionsRationaleActivity";
const ALIAS_NAME = "ViewPermissionUsageActivity";

/**
 * Health Connect's permission sheet links to "the developer's privacy policy",
 * and Google Play requires that link to show it. react-native-health-connect
 * routes the link to MainActivity, which just opens the app, so hand it to a
 * tiny activity that opens the website's /privacy page and finishes.
 *
 * Mods of one type run last-registered-first, so list this plugin *before*
 * react-native-health-connect in app.json: its manifest mod then runs after the
 * library's and can move the intent filter it added.
 */
module.exports = function withHealthConnectRationale(config) {
  const privacyUrl = "https://fitpixel.app/privacy";

  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    const main = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);

    main["intent-filter"] = (main["intent-filter"] ?? []).filter(
      (filter) =>
        !(filter.action ?? []).some(
          (action) => action.$["android:name"] === RATIONALE_ACTION,
        ),
    );

    app.activity = (app.activity ?? []).filter(
      (activity) => activity.$["android:name"] !== `.${ACTIVITY_NAME}`,
    );
    app.activity.push({
      $: {
        "android:name": `.${ACTIVITY_NAME}`,
        "android:exported": "true",
        "android:theme": "@android:style/Theme.Translucent.NoTitleBar",
      },
      "intent-filter": [
        { action: [{ $: { "android:name": RATIONALE_ACTION } }] },
      ],
    });

    // Android 14+ reaches the rationale through this alias instead.
    for (const alias of app["activity-alias"] ?? []) {
      if (alias.$["android:name"] === ALIAS_NAME) {
        alias.$["android:targetActivity"] = `.${ACTIVITY_NAME}`;
      }
    }
    return cfg;
  });

  return withDangerousMod(config, [
    "android",
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error("android.package is required");
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app/src/main/java",
        ...pkg.split("."),
      );
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(
        path.join(dir, `${ACTIVITY_NAME}.kt`),
        `package ${pkg}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

/** Generated by plugins/with-health-connect-rationale.js. */
class ${ACTIVITY_NAME} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    try {
      startActivity(Intent(Intent.ACTION_VIEW, Uri.parse("${privacyUrl}")))
    } finally {
      finish()
    }
  }
}
`,
      );
      return cfg;
    },
  ]);
};
