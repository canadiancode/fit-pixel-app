"""Import the FitPixel character art into the app.

Crops every layer to the box the character uses, halves it (the art's own
pixels are ~16px blocks, so it stays crisp), writes it to
assets/pixel/<layer>/<id>.png and regenerates
features/pixel/character-art.generated.ts (Metro needs static requires).

Backgrounds and held items are not part of this set; they keep their own
canvas (see features/pixel/layer-assets.ts).

Usage (needs Pillow):
  python3 scripts/import-pixel-art.py <path to FitPixel_Avatar>
"""
import re
import sys
from pathlib import Path

from PIL import Image

APP = Path(__file__).resolve().parent.parent
ASSETS = APP / "assets" / "pixel"
GENERATED = APP / "features" / "pixel" / "character-art.generated.ts"
CHARACTER_LAYERS = ["body", "eyes", "nose", "mouth", "hair", "top", "bottom", "shoes"]

# Union of every layer's opaque bounds on the 1060x1484 source canvas is
# (217, 3, 843, 1387); pad to a round box. Keep in sync with
# PIXEL_FIGURE_SOURCE_CROP in features/pixel/figure-geometry.ts.
CROP = (200, 0, 860, 1400)
SCALE = 0.5
OUT_SIZE = (int((CROP[2] - CROP[0]) * SCALE), int((CROP[3] - CROP[1]) * SCALE))

GENDER = {"Masc": "m", "Femme": "f"}
SIZE = {"Small": "small", "Med": "medium", "Big": "big"}
GARMENT = {
    "BegTShirt": ("top", "beg-tee"),
    "BegTank": ("top", "beg-tank"),
    "CasHood": ("top", "cas-hood"),
    "CasTank": ("top", "cas-tank"),
    "CasTanks": ("top", "cas-tank"),
    "BegShorts": ("bottom", "beg-shorts"),
    "BegSweats": ("bottom", "beg-sweats"),
    "CasShorts": ("bottom", "cas-shorts"),
    "CasTight": ("bottom", "cas-tight"),
}
# Shoe styles come from the folder: the file names inside are mislabelled.
SHOE_FOLDER = {
    "FP_Beg_Sneakers_A": "beg-a",
    "FP_BegSneakers_B": "beg-b",
    "FP_CasSneakers_A": "cas-a",
    "FP_CasSneakers_B": "cas-b",
}
# "Bed" is the blue pair of femme sweats.
COLOR_FIX = {"bed": "blue", "redhead": "red"}


def color(raw: str) -> str:
    c = raw.lower()
    return COLOR_FIX.get(c, c)


def classify(p: Path) -> tuple[str, str]:
    stem = p.stem
    parent = p.parent.name
    if m := re.fullmatch(r"FP_(Small|Med|Big)Body_(Masc|Femme)_Tone_([A-D])", stem):
        size, g, tone = m.groups()
        return "body", f"body-{GENDER[g]}-{SIZE[size]}-{tone.lower()}"
    if m := re.fullmatch(r"FP_(\w+?)_(Masc|Femme)_(\w+)", stem):
        garment, g, col = m.groups()
        layer, style = GARMENT[garment]
        return layer, f"{layer}-{GENDER[g]}-{style}-{color(col)}"
    if parent in SHOE_FOLDER:
        col = stem.rsplit("_", 1)[1]
        return "shoes", f"shoes-{SHOE_FOLDER[parent]}-{color(col)}"
    if m := re.fullmatch(r"FP_Eyes_(\d)_Tone_([A-D])", parent):
        shape, tone = m.groups()
        col = stem.rsplit("_", 1)[1]
        return "eyes", f"eyes-{shape}-{color(col)}-{tone.lower()}"
    if m := re.fullmatch(r"FP_(Mouth|Nose)_(\d)_Tone_([A-Da-d])", stem):
        part, shape, tone = m.groups()
        layer = part.lower()
        return layer, f"{layer}-{shape}-{tone.lower()}"
    if m := re.fullmatch(r"FP_(Short|Med|Long)Hair_(\d)_(\w+)", stem):
        length, n, col = m.groups()
        return "hair", f"hair-{length.lower()}-{n}-{color(col)}"
    raise SystemExit(f"unclassified: {p}")


def main() -> None:
    src = Path(sys.argv[1])
    for layer in CHARACTER_LAYERS:
        for old in (ASSETS / layer).glob("*.png"):
            old.unlink()

    manifest: dict[str, list[str]] = {layer: [] for layer in CHARACTER_LAYERS}
    for p in sorted(src.rglob("*.png")):
        layer, name = classify(p)
        if name in manifest[layer]:
            raise SystemExit(f"duplicate {name} from {p}")
        out = ASSETS / layer / f"{name}.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        im = Image.open(p).convert("RGBA").crop(CROP).resize(OUT_SIZE, Image.LANCZOS)
        im.save(out, optimize=True)
        manifest[layer].append(name)

    lines = [
        "// Generated by scripts/import-pixel-art.py. Do not edit by hand.",
        f"// Every image is {OUT_SIZE[0]}x{OUT_SIZE[1]} (see figure-geometry.ts).",
        "",
        "export const CHARACTER_ART = {",
    ]
    for layer in CHARACTER_LAYERS:
        lines.append(f"  {layer}: {{")
        for name in sorted(manifest[layer]):
            lines.append(f'    "{name}": require("@/assets/pixel/{layer}/{name}.png"),')
        lines.append("  },")
    lines.append("} as const;")
    GENERATED.write_text("\n".join(lines) + "\n")
    print({k: len(v) for k, v in manifest.items()}, OUT_SIZE)


if __name__ == "__main__":
    main()
